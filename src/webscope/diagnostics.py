# Сертификатные ошибки — общая причина «https сломан».
_CERT_RE = re.compile(r"ERR_CERT_|ERR_SSL_|ERR_BAD_SSL")
_CODE_RE = re.compile(r"net::(ERR_[A-Z_]+)")

_HTTP_HINTS: dict[int, tuple[str, str]] = {
    401: ("страница требует авторизацию", "укажите логин и пароль для авторизации или откройте страницу"),
    403: ("доступ запрещён", "сервер запретил доступ к странице — проверьте настройки"),
    404: ("страница не найдена", "проверьте адрес: страницы, возможно, не существует"),
    410: ("страница удалена", "страница была удалена с сервера"),
    429: ("слишком много запросов", "сервер ограничил частоту обращений — повторите позже"),
    500: ("ошибка на сервере", "сломан сам сайт — сообщите администрации"),
    502: ("сервер-посредник не получил ответ", "вышестоящий сервер недоступен"),
    503: ("сервис временно недоступен", "сайт на обслуживании — повторите позже"),
    504: ("сервер не ответил вовремя", "вышестоящий сервер не ответил — повторите позже"),
}


def diagnose_navigation_error(url: str, exc: Exception, *, timeout_ms: int = 30_000) -> str:
    """Переводит ошибку ``page.goto`` в причину, понятную владельцу сайта.

    Возвращает сообщение вида «Не удалось открыть …: домен не найден (…)».
    """
    text = str(exc)
    seconds = max(1, round(timeout_ms / 1000))

    # Таймаут Playwright: net::-кода может не быть вовсе.
    if "Timeout" in text or "timeout" in text:
        return (
            f"Не удалось открыть {url}: страница не загрузилась за {seconds} с. "
            "Сервер перегружен или отвечает слишком долго — повторите позже."
        )

    code_match = _CODE_RE.search(text)
    code = code_match.group(1) if code_match else ""

    if _CERT_RE.search(text) or code.startswith("ERR_CERT"):
        return (
            f"Не удалось открыть {url}: сломан HTTPS-сертификат. "
            "Браузер не доверяет сертификату (истёк или выпущен неизвестным центром) — "
            "проверьте его у хостинга."
        )

    if code in _NET_ERRORS:
        reason, hint = _NET_ERRORS[code]
        return f"Не удалось открыть {url}: {reason}. {hint}."

    if code:
        return f"Не удалось открыть {url}: сетевая ошибка ({code}). {text[:200]}"

    return f"Не удалось открыть {url}: {text[:300]}"


def diagnose_http_error(url: str, status: int) -> str:
    """Переводит HTTP-статус ошибки в причину."""
    reason, hint = _HTTP_HINTS.get(status, (f"сервер вернул ошибку {status}", "проверьте адрес и доступность страницы"))
    return f"Не удалось открыть {url}: {reason} (HTTP {status}). {hint}."
